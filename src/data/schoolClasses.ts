export function buildStudentsForClass(classId: string, rawList: Array<{ stt: number; name: string; dob: string; gender: 'Nam' | 'Nữ'; ethnicity?: string }>): Student[] {
  return rawList.map((item) => ({
    id: `stu_${classId.toLowerCase()}_${item.stt.toString().padStart(2, '0')}`,
    stt: item.stt,
    name: item.name,
    dob: item.dob,
    gender: item.gender,
    group: assignGroup(item.stt),
    roleInGroup: item.stt === 1 ? 'Lớp trưởng' : item.stt === 2 ? 'Lớp phó' : 'Thành viên',
    classId: classId,
  }));
}

